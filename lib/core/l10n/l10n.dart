  AppLanguage _currentLanguage = AppLanguage.en;
  AppLanguage get currentLanguage => _currentLanguage;

  LocalizationService() {
    _loadLanguage();
  }

  void _loadLanguage() async {
    final prefs = await SharedPreferences.getInstance();
    final langCode = prefs.getString('language_code') ?? 'en';
    _currentLanguage = AppLanguage.values.firstWhere(
      (l) => l.name == langCode,
      orElse: () => AppLanguage.en
    );
    notifyListeners();
  }

  Future<void> setLanguage(AppLanguage language) async {
    _currentLanguage = language;
    final prefs = await SharedPreferences.getInstance();
    await prefs.setString('language_code', language.name);
    notifyListeners();
  }

  String translate(String key) {
    return _translations[_currentLanguage.name]?[key] ?? 
           _translations['en']?[key] ?? key;
  }
  TextDirection get textDirection => 
    _currentLanguage == AppLanguage.ar ? TextDirection.rtl : TextDirection.ltr;
}

extension TranslateExtension on String {
  String tr(BuildContext context) {
    return Provider.of<LocalizationService>(context, listen: false).translate(this);
  }
